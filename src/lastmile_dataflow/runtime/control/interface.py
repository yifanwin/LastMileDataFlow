"""Semantic position targets; physical joints and dataset layouts stay separate."""
from dataclasses import dataclass, field
from typing import Protocol

import numpy as np


@dataclass
class RobotCommand:
    base_xyyaw: object = None
    lift: float | None = None
    arm_q: dict = field(default_factory=dict)
    gripper_width: dict = field(default_factory=dict)


class RobotInterface(Protocol):
    arms: tuple
    camera_names: dict
    observation_camera: str
    initial_base_field: str
    base_body: str
    open_grip: float
    plan_lift_before_close: bool
    lock_base_after_close: bool

    def aim_station(self, initial, anchor): ...
    def copy_control_from(self, other): ...
    def snapshot_control(self): ...
    def restore_control(self, saved): ...
    def control_height(self): ...
    def manipulation_command(self, side, q, grip, height, base=None): ...
    def record_layout(self): ...
    def record_state(self): ...
    def record_action(self, command): ...

    def state(self): ...
    def hold(self): ...
    def base_pose(self): ...
    def arm_positions(self, arm): ...
    def gripper_width(self, arm): ...
    def tcp_site(self, arm): ...
    def finger_bodies(self, arm): ...
    def apply(self, command, *, fixed_base=False): ...


def tcp_matrix(robot, arm):
    site = robot.tcp_site(arm)
    pose = np.eye(4)
    pose[:3, 3] = robot.data.site_xpos[site]
    pose[:3, :3] = robot.data.site_xmat[site].reshape(3, 3)
    return pose
